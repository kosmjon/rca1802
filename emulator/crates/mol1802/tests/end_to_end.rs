//! End-to-end verification (task 11): a hand-written `asm1802` routine
//! and a hand-written MOL1802 version of the same routine, transpiled and
//! assembled, must produce **identical bytes** -- not just "both
//! assemble" -- the strongest available check that `lower.rs`'s tables
//! match real 1802 semantics. Same verify-by-assembling discipline as
//! `fig_forth_matches_the_reference_hex_exactly`-style tests elsewhere in
//! this project, adapted to compare MOL1802 output against hand-written
//! `asm1802` output instead of a scan.
//!
//! The routine: save `D` on the `R2` stack, build the address of a
//! one-byte buffer, stage a literal byte into it, point `X` at it with an
//! explicit `SEX`, send it out over port 4 (`INP`/`OUT`'s one real-world
//! register choice, `R3`), restore `D`, and return. It exercises
//! `D:STK`/`STK:D`, the 16-bit-immediate-to-register and `D`-to-`(Rn)`
//! rows of the Requirement 3 table, and the `PORT(n)`/`xtrack` lookback
//! (Requirement 4.4) against a real-world register choice (`R3`, not a
//! hardcoded one). `STK` never inserts its own `SEX R2`, so the source
//! writes both explicitly, same as the reference.
//!
//! `SEX R3` is written immediately before the `D : PORT(4)` chain, same
//! as the real transcribed PD1802 driver in `docs/scans/` does before its
//! own `OUT 3` calls -- `SEX` once, then `OUT`/`INP`, with nothing from
//! MOL1802's own sugar in between. (A real polling loop between the `SEX`
//! and the `OUT`, as that driver also does in a couple of places, falls
//! outside the one-line lookback and has to be written as a raw
//! pass-through `OUT`/`INP` instead of the `PORT(n)` sugar -- a real,
//! documented limitation of Requirement 4.4's strict one-line rule, not
//! exercised by this particular routine.)

// Not `"\` + newline before the first indented line: Rust's
// string-continuation escape strips leading whitespace from the line
// that follows it too, which would silently un-indent `ORG` into column
// 1 (where `asm1802` would misread it as a label).
const REFERENCE_ASM1802: &str = "\n        ORG 0000H\nBYTE:   DB 0\nSEND:   SEX R2\n        STXD\n        LDI HIGH(BYTE)\n        PHI R3\n        LDI LOW(BYTE)\n        PLO R3\n        LDI #55\n        STR R3\n        SEX R3\n        OUT 4\n        SEX R2\n        IRX\n        LDX\n        RETN\n";

const MOL1802_SOURCE: &str = "\n    ORG 0000H\nBYTE:   DB 0\nSEND:   SEX R2\n    D:STK\n    BYTE : R3\n    #55 : D\n    D : (R3)\n    SEX R3\n    D : PORT(4)\n    SEX R2\n    STK:D\n    RETN\n";

#[test]
fn mol1802_transpile_matches_the_hand_written_asm1802_byte_for_byte() {
    let reference = asm1802::assemble(REFERENCE_ASM1802);
    assert!(
        reference.ok(),
        "reference should assemble cleanly: {:?}",
        reference.errors
    );

    let generated_source = mol1802::transpile(MOL1802_SOURCE)
        .unwrap_or_else(|errs| panic!("mol1802 source should transpile cleanly: {errs:?}"));
    let generated = asm1802::assemble(&generated_source);
    assert!(
        generated.ok(),
        "generated asm1802 should assemble cleanly: {:?}\n{generated_source}",
        generated.errors
    );

    let (ref_lo, ref_hi) = reference.range().expect("reference has bytes");
    let (gen_lo, gen_hi) = generated.range().expect("generated has bytes");
    assert_eq!(
        (ref_lo, ref_hi),
        (gen_lo, gen_hi),
        "both should occupy the same address range"
    );

    let ref_bytes: Vec<u8> = (ref_lo..=ref_hi)
        .map(|a| reference.byte(a).unwrap_or(0))
        .collect();
    let gen_bytes: Vec<u8> = (gen_lo..=gen_hi)
        .map(|a| generated.byte(a).unwrap_or(0))
        .collect();
    assert_eq!(
        ref_bytes, gen_bytes,
        "mol1802-generated bytes should be identical to the hand-written reference\n\
         generated source was:\n{generated_source}"
    );
}
